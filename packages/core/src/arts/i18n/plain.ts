/** 吉凶状态词 → 白话语气 */
const STATE_PLAIN: Record<string, string> = {
  吉: '顺遂，可以推进',
  凶: '要谨慎，容易受阻',
  变数: '有变数，多留意',
  提示: '了解一下即可',
};

/** 干支/五行生克口语化：X生Y → X 在帮 Y；X克Y → X 在压 Y */
function shengKePlain(text: string): string {
  const stems = '甲乙丙丁戊己庚辛壬癸';
  const wuxing = '木火土金水';
  const all = stems + '子丑寅卯辰巳午未申酉戌亥';
  return text
    .replace(new RegExp(`([${stems}${wuxing}])生([${stems}${wuxing}])`, 'g'), '$1 在帮 $2')
    .replace(new RegExp(`([${all}${wuxing}])克([${all}${wuxing}])`, 'g'), '$1 在压 $2');
}

function artLabelZh(art: string): string {
  const map: Record<string, string> = {
    liuyao: '六爻', meihua: '梅花易数', xiaoliuren: '小六壬', qimen: '奇门遁甲',
    liuren: '大六壬', jinkou: '金口诀', bazi: '八字', ziwei: '紫微斗数',
  };
  return map[art] ?? art;
}

/**
 * 白话输出标点规整（防粘连、去重排、规整句末）：
 * - 去除中文标点两侧多余空格；
 * - 同类标点连排去重（。。→。、，，→，、；；→；）；
 * - 异类标点相邻只留后者（。；→；、；。→。、，。→。、：；→；等）；
 * - 句末悬挂的逗/分/句末点统一剥离（由调用方以「；程度。」衔接）。
 */
function cleanPunct(text: string): string {
  return text
    .replace(/ *([，。！？；：、】）]) */g, '$1')
    .replace(/ *([（【])/g, '$1')
    .replace(/([，。！？；：、])\1+/g, '$1')
    .replace(/([，。！？；：、])([，。！？；：、])/g, '$2')
    .replace(/[，。！？；：、]+$/, '')
    .replace(/(?:…+|[.…]{3,})+$/, '')
    .replace(/(?:——|-{2,})+$/, '')
    .trim();
}

/** 汉字范围（右边界判定用：术语后紧贴汉字时视为单词内部，不拆分，保持干支/原文原样） */
const CJK = '\u4e00-\u9fff';

/** 转义正则元字符（术语均为汉字短语，防御性处理） */
function escapeRe(s: string): string {
  return s.replace(/[.*+?^$(){}[\]\\|]/g, '\\$&');
}

/** 把一条规则文本转成白话（数字/干支/结论保持不动）。按词长降序替换，避免长词被短词先拆。 */
export function plainRuleText(art: string, r: RuleHit): string {
  let text = r.text;
  const ordered = [...TERM_PLAIN].sort((a, b) => b[0].length - a[0].length);
  for (const [term, plain] of ordered) {
    // 右边界替换：术语后紧贴汉字（如「涉害课」「四孟位」「取用神亥」「旬空亡」）视为词内部不拆，
    // 避免「。；」式的恶性再替换（如「四四孟位」「为用神课」「暂时落空、力不从心亡」）
    text = text.replace(new RegExp(`${escapeRe(term)}(?![${CJK}])`, 'g'), plain);
  }
  text = shengKePlain(text);
  const sev = STATE_PLAIN[r.severity];
  const head = cleanPunct(`白话精讲（${artLabelZh(art)}）· ${text}`);
  return `${head}；${sev ?? '一般性提示'}。`;
}

/** 白话总评：一眼看懂这盘的整体倾向 */
export function plainSummary(art: string, rules: RuleHit[]): string {
  const ji = rules.filter((r) => r.severity === '吉').length;
  const xiong = rules.filter((r) => r.severity === '凶').length;
  const bian = rules.filter((r) => r.severity === '变数').length;
  const overall = ji > xiong ? '整体偏顺' : xiong > ji ? '整体要谨慎' : '吉凶参半、顺势而为';
  const noXiong = xiong === 0 ? '没有明显的凶信号，可以按计划推进。' : '';
  return `用${artLabelZh(art)}看这一盘：${overall}（${ji} 条偏吉 / ${xiong} 条偏凶 / ${bian} 条有变数）。${noXiong}\n详情见下方各条的「白话精讲」。`;
}