function mapCharacters(text: string, map: Readonly<Record<string, string>>): string {
  return [...text].map((character) => map[character] ?? character).join('');
}

/** 把古籍异体字折叠到稳定的规范字形。 */
export function foldVariants(text: string): string {
  return mapCharacters(text, VARIANT_TO_CANONICAL);
}

/** 把异体字与常见繁体字折叠为检索用简体字形。 */
export function normalizeSearchText(text: string): string {
  return mapCharacters(foldVariants(text), TRADITIONAL_TO_SIMPLIFIED);
}

/** 在不改变展示原文的前提下进行字形无关的包含匹配。 */
export function includesNormalizedText(text: string, query: string): boolean {
  const normalizedQuery = normalizeSearchText(query.trim());
  return normalizedQuery.length === 0 || normalizeSearchText(text).includes(normalizedQuery);
}
